CREATE TABLE users (
    user_id VARCHAR(20) PRIMARY KEY,
    password_hash VARCHAR(255) NOT NULL,
    user_name VARCHAR(255) NOT NULL,
    role_cd VARCHAR(20) NOT NULL
);
CREATE TABLE courses (
    course_inst_id VARCHAR(36) PRIMARY KEY,
    course_code VARCHAR(10) NOT NULL UNIQUE,
    professor_id VARCHAR(20) NOT NULL,
    course_title VARCHAR(100) NOT NULL,
    course_category VARCHAR(255) NOT NULL,
    grading_type VARCHAR(255) NOT NULL,
    max_capacity INTEGER NOT NULL,
    min_enrollment INTEGER NOT NULL,
    credit INTEGER NOT NULL,
    active_cnt INTEGER NOT NULL,
    classroom VARCHAR(255) NOT NULL,
    course_status VARCHAR(20) NOT NULL,
    course_created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    course_updated_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE waiting_tickets (
    ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_type VARCHAR(255) NOT NULL,
    requester_user_id VARCHAR(20),
    session_ref VARCHAR(64),
    anon_context_id VARCHAR(64),
    anon_proof_verifier VARCHAR(255),
    credential_expires_at TIMESTAMP WITH TIME ZONE,
    proof_expires_at TIMESTAMP WITH TIME ZONE,
    target_course_inst_id VARCHAR(36),
    course_code_snapshot VARCHAR(10),
    ticket_issued_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status_cd VARCHAR(20) NOT NULL,
    processing_started_at TIMESTAMP WITH TIME ZONE,
    processing_finished_at TIMESTAMP WITH TIME ZONE,
    result_cd VARCHAR(255),
    retry_count INTEGER NOT NULL,
    owner_worker_ref VARCHAR(255),
    generation_no INTEGER NOT NULL,
    lease_info VARCHAR(255),
    slot_claim_ref VARCHAR(255)
);
CREATE TABLE access_sessions (
    session_id VARCHAR(64) PRIMARY KEY,
    user_id VARCHAR(20) NOT NULL,
    role_cd VARCHAR(20) NOT NULL,
    login_ticket_id BIGINT NOT NULL,
    logged_in_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    session_status VARCHAR(255) NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    revoke_reason VARCHAR(255),
    first_token_issued_at TIMESTAMP WITH TIME ZONE,
    entered_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE refresh_token_records (
    refresh_token_hash VARCHAR(255) PRIMARY KEY,
    session_id VARCHAR(64) NOT NULL,
    issued_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE enrollments (
    student_id VARCHAR(20) NOT NULL,
    course_inst_id VARCHAR(36) NOT NULL,
    enroll_status VARCHAR(20) NOT NULL,
    enroll_type VARCHAR(255) NOT NULL,
    enrolled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    assigned_by_user_id VARCHAR(20),
    source_ticket_id BIGINT,
    PRIMARY KEY (student_id, course_inst_id)
);
CREATE TABLE service_settings (
    id BIGINT PRIMARY KEY,
    concurrency_limit INTEGER NOT NULL,
    last_changed_by VARCHAR(20),
    last_changed_at TIMESTAMP WITH TIME ZONE
);